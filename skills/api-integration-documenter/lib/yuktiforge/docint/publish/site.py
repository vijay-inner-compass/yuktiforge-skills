"""Navigable HTML documentation site (docs-site/) and the single-file HTML used for the PDF/DOCX document pack. Markdown stays the canonical editable source; HTML is generated from it."""
from __future__ import annotations

import html
import json
import re
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from yuktiforge.docint.docgen.doc import Document
from yuktiforge.docint.publish import tools
from yuktiforge.docint.publish.render_diagrams import DiagramResult
from yuktiforge.errors import YuktiForgeError

DOC_DIAGRAMS: dict[str, tuple[str, ...]] = {
    "hld": ("context", "container", "integration", "deployment", "dfd-0", "dfd-1"), "lld": ("components-*", "erd", "dfd-2-*"), "system-architecture": ("context", "container", "technology"),
    "solution-architecture": ("container", "integration"), "technology-architecture": ("technology", "deployment"), "api-catalog": ("integration",), "data-dictionary": ("erd",),
    "database-doc": ("erd",), "code-explanation": ("components-*",), "dataflow": ("dfd-0", "dfd-1", "dfd-2-*"), "srs-draft": ("context", "dfd-0"), "brd-draft": ("context",),
    "functional-spec": ("dfd-1",), "use-cases": ("dfd-0",), "business-rule-catalog": ("erd",),
}
_ID = re.compile(r'(\bid=")([^"]+)(")')
_HREF = re.compile(r'(\bhref="#)([^"]+)(")')


@dataclass
class DocPage:
    doc: Document
    md: str
    stem: str                       # file stem, e.g. hld.developer.deep
    html: str = ""                  # body fragment


def diagrams_for(doc_type: str, results: list[DiagramResult]) -> list[DiagramResult]:
    pats = DOC_DIAGRAMS.get(doc_type, ())
    out = []
    for r in results:
        if any((r.spec.id.startswith(p[:-1]) if p.endswith("*") else r.spec.id == p) for p in pats):
            out.append(r)
    return out


def md_to_html(md: str) -> str:
    if not tools.which("pandoc"):
        raise YuktiForgeError("HTML export needs pandoc, which was not found on PATH")
    p = tools.run(["pandoc", "-f", "gfm-autolink_bare_uris", "-t", "html5", "--wrap=none"], timeout=120, stdin=md)
    if p.returncode != 0:
        raise YuktiForgeError(f"pandoc failed: {p.stderr.strip()[:200]}")
    return p.stdout


def prefix_ids(fragment: str, prefix: str) -> str:
    """Make every id and in-page link of one chapter unique inside a single-file pack."""
    return _HREF.sub(lambda m: f'{m.group(1)}{prefix}{m.group(2)}{m.group(3)}', _ID.sub(lambda m: f'{m.group(1)}{prefix}{m.group(2)}{m.group(3)}', fragment))


def headings(fragment: str, level: int = 2) -> list[tuple[str, str]]:
    return [(m.group(1), re.sub(r"<[^>]+>", "", m.group(2)).strip()) for m in re.finditer(rf'<h{level} id="([^"]+)"[^>]*>(.*?)</h{level}>', fragment, re.S)]


def esc(t: object) -> str:
    return html.escape(str(t), quote=True)


def figure(r: DiagramResult, base: str, caption_extra: str = "") -> str:
    img = f"{base}{r.spec.id}/diagram.svg"
    inferred = sum(1 for x in (*r.spec.model.components, *r.spec.model.relations) if x.evidence.status == "inferred")
    return (f'<figure id="fig-{esc(r.spec.id)}"><img src="{esc(img)}" alt="{esc(r.spec.title)}: {len(r.spec.model.components)} elements, {len(r.spec.model.relations)} relations">'
            f'<figcaption><b>{esc(r.spec.title)}</b> (view {esc(r.spec.view)}). {inferred} of {len(r.spec.model.components) + len(r.spec.model.relations)} elements are inferred (dashed). '
            f'Editable sources: <a href="{esc(base)}{esc(r.spec.id)}/architecture.json">architecture.json</a>, <a href="{esc(base)}{esc(r.spec.id)}/diagram.dot">diagram.dot</a>. {caption_extra}</figcaption></figure>')


# ----------------------------------------------------------------------------- the site
def _page(title: str, body: str, nav: str, meta: dict[str, Any], base: str) -> str:
    return f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>{esc(title)}</title>
<link rel="stylesheet" href="{base}assets/site.css"></head><body>
<header class="top"><span class="brand">{esc(meta['repo'])} &mdash; documentation pack</span><span class="meta"><span class="draft">DRAFT</span> &middot; revision {esc(meta['revision'])} &middot; scan {esc(meta['scan'])}</span></header>
<div class="layout"><nav class="side" aria-label="Documentation">{nav}</nav><main>{body}</main></div>
<footer class="bottom">Generated by yuktiforge from the System Knowledge Model. Reconstructed documents are drafts, not approved business requirements. Every statement carries a label and evidence; see the glossary for terms.</footer>
</body></html>
'''


def _nav(pages: list[DocPage], diagrams: list[DiagramResult], base: str, current: str) -> str:
    def li(href: str, text: str, key: str) -> str:
        return f'<li><a href="{base}{esc(href)}"' + (' class="current"' if key == current else "") + f">{esc(text)}</a></li>"
    docs = "".join(li(f"{p.stem}.html", p.doc.title.split(" — ")[0], p.stem) for p in pages)
    dgs = "".join(li(f"diagrams/{r.spec.id}.html", r.spec.title, f"d:{r.spec.id}") for r in diagrams)
    return (f'<ul>{li("index.html", "Overview", "index")}</ul><h3>Documents</h3><ul>{docs}</ul><h3>Diagrams</h3><ul>{dgs}</ul>'
            f'<h3>Reference</h3><ul>{li("glossary.html", "Glossary", "glossary")}{li("traceability.html", "Requirements traceability", "trace")}{li("quality.html", "Validation and coverage", "quality")}</ul>')


def build_site(out: Path, pages: list[DocPage], diagrams: list[DiagramResult], diagrams_dir: Path, glossary: dict, trace: dict, validation: dict, coverage: dict[str, dict],
               unsupported: list[Any], meta: dict[str, Any]) -> list[str]:
    out.mkdir(parents=True, exist_ok=True)
    (out / "assets").mkdir(exist_ok=True)
    shutil.copy2(tools.ASSETS / "site.css", out / "assets" / "site.css")
    (out / "diagrams").mkdir(exist_ok=True)
    for r in diagrams:                                           # diagram files live under diagrams/<id>/ in the site
        dest = out / "diagrams" / r.spec.id
        shutil.copytree(r.dir, dest, dirs_exist_ok=True)
    written = ["assets/site.css"]
    for p in pages:
        p.html = md_to_html(p.md)
    for p in pages:
        rel = diagrams_for(p.doc.doc_type, diagrams)
        figs = "".join(figure(r, "diagrams/") for r in rel)
        toc = "".join(f'<li><a href="#{esc(i)}">{esc(t)}</a></li>' for i, t in headings(p.html, 2))
        body = p.html
        if figs:
            body = body.replace("<h2 ", f'<section aria-label="Related diagrams"><h2 id="related-diagrams">Related diagrams</h2>{figs}</section><h2 ', 1)
        rel_li = '<li><a href="#related-diagrams">Related diagrams</a></li>' if figs else ""
        body = f'<div class="toc"><b>On this page</b><ul>{toc}{rel_li}</ul></div>' + body if toc else body
        (out / f"{p.stem}.html").write_text(_page(p.doc.title, body, _nav(pages, diagrams, "", p.stem), meta, ""), encoding="utf-8")
        written.append(f"{p.stem}.html")
    for r in diagrams:
        rows = "".join(f"<tr><td>{esc(c.name)}</td><td>{esc(c.kind)}</td><td><span class='tag'>{esc(c.evidence.status)}</span></td><td>{esc(', '.join(s.ref for s in c.evidence.sources[:3]))}</td><td>{esc(c.evidence.rationale)}</td></tr>" for c in r.spec.model.components)
        rrows = "".join(f"<tr><td>{esc(next((c.name for c in r.spec.model.components if c.id == x.source), x.source))} &rarr; {esc(next((c.name for c in r.spec.model.components if c.id == x.target), x.target))}</td>"
                        f"<td>{esc(x.label)}</td><td><span class='tag'>{esc(x.evidence.status)}</span></td><td>{esc(', '.join(s.ref for s in x.evidence.sources[:3]))}</td><td>{esc(x.evidence.rationale)}</td></tr>" for x in r.spec.model.relations)
        notes = "".join(f"<li>{esc(n)}</li>" for n in r.spec.notes)
        chk = r.consistency
        body = (f"<h1>{esc(r.spec.title)}</h1><p>View <code>{esc(r.spec.view)}</code>; used by {esc(r.spec.purpose)}. Layout <code>{esc(r.render.get('layout', {}).get('chosen', ''))}</code>.</p>"
                + figure(r, "") .replace('src="', 'src="') + (f"<h2>Notes</h2><ul>{notes}</ul>" if notes else "")
                + f"<h2>Source-to-diagram check</h2><p>{chk['elements']} element(s) and {chk['relations']} relation(s) traced to knowledge-model entities; {len(chk['errors'])} error(s); "
                  f"{chk['relationships_in_scope_not_drawn']} in-scope relationship(s) not drawn.</p>"
                + f"<h2>Elements</h2><table><tr><th>Element</th><th>Kind</th><th>Evidence</th><th>Source</th><th>Rationale</th></tr>{rows}</table>"
                + f"<h2>Relations</h2><table><tr><th>Relation</th><th>Label</th><th>Evidence</th><th>Source</th><th>Rationale</th></tr>{rrows}</table>"
                + "<h2>Editable sources</h2><ul><li><a href='architecture.json'>architecture.json</a> (canonical model: edit this and re-render)</li><li><a href='diagram.dot'>diagram.dot</a> (Graphviz source)</li>"
                  "<li><a href='validation.json'>validation.json</a></li><li><a href='mapping.json'>mapping.json</a> (element to knowledge-model entity)</li><li><a href='diagram.png'>diagram.png</a>, <a href='diagram.pdf'>diagram.pdf</a></li></ul>")
        body = body.replace('src="diagrams/', 'src="').replace('href="diagrams/', 'href="')
        (out / "diagrams" / f"{r.spec.id}.html").write_text(_page(r.spec.title, body.replace(f'{r.spec.id}/', f'{r.spec.id}/'), _nav(pages, diagrams, "../", f"d:{r.spec.id}"), meta, "../"), encoding="utf-8")
        written.append(f"diagrams/{r.spec.id}.html")
    # glossary
    used_by: dict[str, list[str]] = {}
    for p in pages:
        for t in p.doc.glossary_terms:
            used_by.setdefault(t, []).append(p.stem)
    g_rows = "".join(f"<tr id='{esc(t['id'])}'><td>{esc(t['term'])}</td><td><code>{esc(t['id'])}</code></td><td>{esc(t['definition'])}</td><td>" + ", ".join(f"<a href='{esc(s)}.html'>{esc(s.split('.')[0])}</a>" for s in sorted(set(used_by.get(t['id'], [])))) + "</td></tr>" for t in glossary["terms"])
    (out / "glossary.html").write_text(_page("Glossary", f"<h1>Glossary</h1><p>Terms are entities of the System Knowledge Model; the id is the canonical identifier used by every document.</p><table><tr><th>Term</th><th>Id</th><th>Meaning</th><th>Used in</th></tr>{g_rows}</table>", _nav(pages, diagrams, "", "glossary"), meta, ""), encoding="utf-8")
    written.append("glossary.html")
    # traceability
    t_rows = "".join(f"<tr><td>{esc(r['requirement']['name'])}</td><td>{esc(r['requirement']['approval'])}</td><td>{esc(', '.join(c['name'] for c in r['code']) or '-')}</td><td>{esc(', '.join(r['tests_importing_that_code']) or '-')}</td><td>{esc(r['status'])}</td></tr>" for r in trace["requirements"])
    unreq = "".join(f"<li>{esc(a['name'])}</li>" for a in trace["apis_without_a_linked_requirement"])
    (out / "traceability.html").write_text(_page("Requirements traceability", f"<h1>Requirements traceability</h1><blockquote>Links from a requirement to code exist only when a named person made them. Tests are linked by import, which is a hint, not coverage.</blockquote>"
                                                  f"<table><tr><th>Requirement</th><th>Approval</th><th>Code</th><th>Tests importing it</th><th>Status</th></tr>{t_rows or '<tr><td colspan=5>No requirements have been supplied.</td></tr>'}</table><h2>APIs with no linked requirement</h2><ul>{unreq or '<li>none</li>'}</ul>", _nav(pages, diagrams, "", "trace"), meta, ""), encoding="utf-8")
    written.append("traceability.html")
    # quality
    q_rows = "".join(f"<tr><td>{esc(p.doc.title.split(' — ')[0])}</td><td>{esc(p.doc.audience)}/{esc(p.doc.depth)}</td><td>{coverage[p.doc.doc_id]['statements']}</td><td>{coverage[p.doc.doc_id]['with_evidence']}</td><td>{coverage[p.doc.doc_id]['unknown_or_needs_validation']}</td>"
                     f"<td>{len(validation['documents'][p.doc.doc_id]['defects'])}</td><td>{len(p.doc.gaps)}</td></tr>" for p in pages)
    uns = "".join(f"<li><b>{esc(u.view)}</b> ({esc(u.id)}): {esc(u.reason)}</li>" for u in unsupported)
    (out / "quality.html").write_text(_page("Validation and coverage", f"<h1>Validation and coverage</h1><table><tr><th>Document</th><th>Profile</th><th>Statements</th><th>With evidence</th><th>Unknown / needs validation</th><th>Defects</th><th>Gaps</th></tr>{q_rows}</table>"
                                                                      f"<h2>Diagram views not generated</h2><ul>{uns or '<li>none</li>'}</ul>", _nav(pages, diagrams, "", "quality"), meta, ""), encoding="utf-8")
    written.append("quality.html")
    # index
    d_list = "".join(f"<li><a href='{esc(p.stem)}.html'>{esc(p.doc.title)}</a> &mdash; <span class='draft'>{esc(p.doc.status.split(';')[0])}</span></li>" for p in pages)
    g_list = "".join(f"<li><a href='diagrams/{esc(r.spec.id)}.html'>{esc(r.spec.title)}</a> ({esc(r.spec.view)})</li>" for r in diagrams)
    (out / "index.html").write_text(_page(f"{meta['repo']} documentation pack", f"<h1>{esc(meta['repo'])}: documentation pack</h1><blockquote>This pack is reconstructed from source code. Reconstructed requirement documents are DRAFTS and are not approved business requirements. "
                                                                         f"Business intent, security posture and compliance are not established by code and are marked UNKNOWN or NEEDS_STAKEHOLDER_VALIDATION.</blockquote><h2>Documents</h2><ul>{d_list}</ul><h2>Diagrams</h2><ul>{g_list}</ul>"
                                                                         f"<h2>How to read this</h2><p>Every statement ends with a label: VERIFIED (observed in source), INFERRED (derived by a stated rule), USER_SUPPLIED, UNKNOWN, NEEDS_STAKEHOLDER_VALIDATION. Citations give file and line.</p>", _nav(pages, diagrams, "", "index"), meta, ""), encoding="utf-8")
    written.append("index.html")
    return written


# ----------------------------------------------------------------------------- link checker
_REF = re.compile(r'(?:href|src)="([^"#][^"]*|#[^"]+)"')


def check_links(root: Path) -> dict[str, Any]:
    """Every relative href/src resolves to a file inside the site, and every #anchor exists in its target page. External links are listed, not followed."""
    problems: list[str] = []
    external: set[str] = set()
    ids_cache: dict[Path, set[str]] = {}

    def ids_of(p: Path) -> set[str]:
        if p not in ids_cache:
            ids_cache[p] = set(re.findall(r'\bid="([^"]+)"', p.read_text(encoding="utf-8", errors="replace"))) if p.suffix == ".html" else set()
        return ids_cache[p]

    root = root.resolve()
    pages = sorted(root.rglob("*.html"))
    n = 0
    for page in pages:
        text = page.read_text(encoding="utf-8")
        for ref in _REF.findall(text):
            n += 1
            if re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", ref):
                external.add(ref)
                continue
            target, _, frag = ref.partition("#")
            dest = page.resolve() if not target else (page.parent / target).resolve()
            try:
                dest.relative_to(root)
            except ValueError:
                problems.append(f"{page.relative_to(root)}: {ref} leaves the site")
                continue
            if not dest.exists():
                problems.append(f"{page.relative_to(root)}: {ref} does not exist")
            elif frag and dest.suffix == ".html" and frag not in ids_of(dest):
                problems.append(f"{page.relative_to(root)}: anchor #{frag} not found in {dest.name}")
    return {"pages": len(pages), "links_checked": n, "problems": problems, "external_links": sorted(external)}
