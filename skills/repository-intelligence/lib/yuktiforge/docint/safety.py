"""Safety rules for scanning untrusted repositories. The scanner only READS text files below the repository root: it never follows symlinks,
never reads secret-like or binary files, never executes, imports or compiles anything it finds, and never lets a file name or a literal
inside a file place anything in its output that could be mistaken for an instruction or leak a credential."""
from __future__ import annotations

import fnmatch
import re
import unicodedata
from dataclasses import dataclass

