_GENERATED_NAME = re.compile(r"(\.min\.(js|css)|\.pb\.go|_pb2(_grpc)?\.pyi?|\.designer\.cs|\.g\.cs|\.generated\.\w+|\.bundle\.js|\.map)$", re.I)
_GENERATED_HEAD = re.compile(r"(@generated|<auto-generated|DO NOT EDIT|Code generated by|This file was automatically generated|auto-generated by)", re.I)
_SECRET_NAMES = ("id_rsa", "id_dsa", "id_ecdsa", "id_ed25519")
_SECRET_EXT = frozenset({".pem", ".key", ".p12", ".pfx", ".jks", ".keystore", ".ppk", ".kdbx", ".gpg", ".asc"})
_SECRET_BASENAMES = frozenset({".npmrc", ".pypirc", ".netrc", ".dockercfg", ".htpasswd", "credentials", "credentials.json", "service-account.json", "kubeconfig", ".boto"})
_CONFIG_EXT = frozenset({".json", ".yaml", ".yml", ".toml", ".ini", ".cfg", ".conf", ".properties", ".xml", ".env", ".txt"})
_SECRETISH = re.compile(r"(secret|credential|passwd|password|private[-_]?key|token)", re.I)
_ENV_TEMPLATE = re.compile(r"\.(example|sample|template|dist|defaults?|tmpl)(\.|$)", re.I)      # a template (`.env.example`, `secrets.example.yaml`) holds placeholders, not secrets


def is_secret_like(rel: str) -> bool:
    """Judged by NAME only: the content of such a file is never opened."""
    name = rel.rsplit("/", 1)[-1]
    low = name.lower()
    ext = low[low.rfind("."):] if "." in low else ""
    if low == ".env" or (low.startswith(".env.") and not _ENV_TEMPLATE.search(low)):
        return True
    if low in _SECRET_BASENAMES or ".aws/" in rel or rel.startswith(".ssh/") or "/.ssh/" in rel:
        return True
    if any(low == n or low.startswith(n + ".") for n in _SECRET_NAMES):
        return True
    if ext in _SECRET_EXT:
        return True
    if ext in _CONFIG_EXT and _SECRETISH.search(low.rsplit(".", 1)[0]) and not _ENV_TEMPLATE.search(low):
        return True
    return False


def is_generated_name(name: str) -> bool:
    return bool(_GENERATED_NAME.search(name))


def has_generated_header(head: str) -> bool:
    return bool(_GENERATED_HEAD.search(head[:2048]))


def looks_binary(head: bytes, ext: str) -> bool:
    return ext in BINARY_EXT or b"\x00" in head[:8192]


_BIDI = set("‪‫‬‭‮⁦⁧⁨⁩‎‏؜")


def unsafe_name(rel: str) -> bool:
    """A name containing control characters, newlines or bidirectional overrides: it could forge lines in a report or reorder what a human reads."""
    return any(ord(c) < 0x20 or ord(c) == 0x7F or c in _BIDI or unicodedata.category(c) in ("Cc", "Cf") for c in rel)


def safe_display(text: str) -> str:
    """Make any string safe to put in a report: control and bidi characters become visible escapes."""
    return "".join(c if not (ord(c) < 0x20 or ord(c) == 0x7F or c in _BIDI or unicodedata.category(c) in ("Cc", "Cf")) or c == "\t" else f"\\u{ord(c):04x}" for c in text)


_SECRET_PARAM = re.compile(r"^(key|api[_-]?key|token|access[_-]?token|secret|password|passwd|pwd|auth|signature|sig|sas|code|session)$", re.I)


_URL_PARTS = re.compile(r"^(?:([A-Za-z][A-Za-z0-9+.-]*):)?(?://([^/?#]*))?([^?#]*)(?:\?([^#]*))?(?:#.*)?$", re.S)


def redact_url(url: str) -> str:
    """Remove credentials from a URL literal before it is stored: user:password@, the values of secret-looking query parameters, and the fragment.
    (Plain string handling, deliberately: this package imports no network-capable module.)"""
    m = _URL_PARTS.match(url.strip())
    if m is None:
        return "<unparseable-url>"
    scheme, netloc, path, query = m.group(1), m.group(2), m.group(3) or "", m.group(4)
    out = (scheme + ":" if scheme else "") + ("//" + netloc.rsplit("@", 1)[-1] if netloc is not None else "") + path
    if query:
        out += "?" + "&".join(f"{p.split('=', 1)[0]}=<redacted>" if _SECRET_PARAM.match(p.split("=", 1)[0]) else p for p in query.split("&") if p)
    return out


def language_for(rel: str) -> str | None:
    name = rel.rsplit("/", 1)[-1]
    dot = name.rfind(".")
    return EXT_TO_LANGUAGE.get(name[dot:].lower()) if dot >= 0 else None


# ------------------------------------------------------------------------------------------------ .gitignore
def _translate(pattern: str) -> re.Pattern[str]:
    i, n, out = 0, len(pattern), []
    while i < n:
        c = pattern[i]
        if c == "*":
            if pattern[i:i + 3] == "**/":
                out.append("(?:.*/)?")
                i += 3
                continue
            if pattern[i:i + 2] == "**":
                out.append(".*")
                i += 2
                continue
            out.append("[^/]*")
        elif c == "?":
            out.append("[^/]")
        elif c == "[":
            j = pattern.find("]", i + 2)
            if j < 0:
                out.append(re.escape(c))
            else:
                body = pattern[i + 1:j]
                body = "^" + body[1:] if body[:1] in ("!", "^") else body
                out.append("[" + body.replace("\\", "\\\\") + "]")
                i = j
        elif c == "\\" and i + 1 < n:
            out.append(re.escape(pattern[i + 1]))
            i += 1
        else:
            out.append(re.escape(c))
        i += 1
    return re.compile("".join(out) + r"\Z")


@dataclass(frozen=True)
class _Rule:
    base: str                   # directory (relative, "" for root) the .gitignore lives in
    regex: re.Pattern[str]
    negate: bool
    dir_only: bool
    anchored: bool


def parse_gitignore(text: str, base: str) -> list[_Rule]:
    rules = []
    for raw in text.splitlines()[:5000]:
        line = raw.rstrip("\r")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line.endswith("\\ "):
            line = line.rstrip()
        neg = line.startswith("!")
        if neg:
            line = line[1:]
        dir_only = line.endswith("/")
        line = line.rstrip("/")
        if not line:
            continue
        anchored = "/" in line
        line = line.lstrip("/")
        try:
            rules.append(_Rule(base, _translate(line), neg, dir_only, anchored))
        except re.error:
            continue
    return rules


def ignored_by(rules: list[_Rule], rel: str, is_dir: bool) -> bool:
    """Git semantics, subset: patterns apply in order across .gitignore files from the root down; the last match wins; a pattern containing a
    slash is anchored to its .gitignore's directory; otherwise it matches a name at any depth; a trailing slash matches directories only."""
    verdict = False
    for r in rules:
        if r.dir_only and not is_dir:
            continue
        if r.base and not (rel == r.base or rel.startswith(r.base + "/")):
            continue
        sub = rel[len(r.base) + 1:] if r.base else rel
        target = sub if r.anchored else sub.rsplit("/", 1)[-1]
        if r.regex.match(target):
            verdict = not r.negate
    return verdict


def fnmatch_any(name: str, patterns: tuple[str, ...]) -> bool:
    return any(fnmatch.fnmatchcase(name, p) for p in patterns)


# ------------------------------------------------------------------------------------------------ secret scrubbing of extracted text
_SECRET_PATTERNS = [
    re.compile(r"AKIA[0-9A-Z]{16}"),
    re.compile(r"\b(?:ghp|gho|ghu|ghs|ghr|github_pat)_[A-Za-z0-9_]{20,}"),
    re.compile(r"\bsk-[A-Za-z0-9_-]{20,}"),
    re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}"),
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{5,}"),
]
_KV_SECRET = re.compile(r"(?i)\b(password|passwd|pwd|secret|api[_-]?key|access[_-]?key|token|auth)\b(\s*[=:]\s*)(['\"]?)([^\s'\",;)]{3,})")
_URL_CRED = re.compile(r"(?i)\b([a-z][a-z0-9+.-]*://)([^/\s:@]+):([^/\s@]+)@")


def scrub_text(text: str) -> str:
    """Mask credentials that appear inside text COPIED from a repository (SQL snippets, signatures, default values) before it is written to any output."""
    if not text:
        return text
    t = _URL_CRED.sub(r"\1<redacted>@", text)
    for p in _SECRET_PATTERNS:
        t = p.sub("<redacted-secret>", t)
    return _KV_SECRET.sub(lambda m: f"{m.group(1)}{m.group(2)}{m.group(3)}<redacted>", t)
