@dataclass(frozen=True)
class Limits:
    max_file_bytes: int = 1_000_000
    max_files: int = 100_000
    max_total_bytes: int = 1_000_000_000      # sum of the sizes of files that are read
    max_depth: int = 64
    max_line_chars: int = 5_000               # longer lines are truncated before pattern matching (regex safety), the file is flagged
    max_facts_per_file: int = 20_000


DEFAULT_LIMITS = Limits()

